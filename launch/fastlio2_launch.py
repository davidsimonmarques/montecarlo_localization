"""Launch standalone FAST-LIO2 LiDAR-Inertial Odometry and Bridge."""

import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.conditions import IfCondition
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue


def generate_launch_description():
    """Generate launch description for standalone FAST-LIO2 odometry pipeline."""
    pkg_share = get_package_share_directory('montecarlo_localization')

    default_params = os.path.join(pkg_share, 'config', 'fastlio2_params.yaml')
    default_rviz = os.path.join(pkg_share, 'rviz', 'mcl_visualization.rviz')

    # Launch arguments
    params_arg = DeclareLaunchArgument(
        'params_file',
        default_value=default_params,
        description='Path to YAML configuration for fastlio_bridge_node and laser_mapping'
    )
    use_sim_time_arg = DeclareLaunchArgument(
        'use_sim_time',
        default_value='false',
        description='Use simulation clock (/clock) if true'
    )
    scan_topic_arg = DeclareLaunchArgument(
        'scan_topic',
        default_value='/scan',
        description='Input 2D LaserScan topic'
    )
    imu_topic_arg = DeclareLaunchArgument(
        'imu_topic',
        default_value='/imu/data',
        description='Input IMU topic'
    )
    odom_topic_arg = DeclareLaunchArgument(
        'odom_topic',
        default_value='/odom',
        description='Output odometry topic generated by FAST-LIO2 bridge'
    )
    publish_odom_tf_arg = DeclareLaunchArgument(
        'publish_odom_tf',
        default_value='true',
        description='Whether to broadcast odom -> base_link TF'
    )
    use_rviz_arg = DeclareLaunchArgument(
        'use_rviz',
        default_value='false',
        description='Whether to launch RViz2 for visualization'
    )
    rviz_config_arg = DeclareLaunchArgument(
        'rviz_config',
        default_value=default_rviz,
        description='Path to RViz2 configuration file'
    )

    params_file = LaunchConfiguration('params_file')
    use_sim_time = LaunchConfiguration('use_sim_time')
    scan_topic = LaunchConfiguration('scan_topic')
    imu_topic = LaunchConfiguration('imu_topic')
    odom_topic = LaunchConfiguration('odom_topic')

    # 1. Bridge Node: converts /scan + /imu/data -> PointCloud2 + adapts /Odometry to odom_out_topic + TF
    fastlio_bridge_node = Node(
        package='montecarlo_localization',
        executable='fastlio_bridge_node',
        name='fastlio_bridge_node',
        output='screen',
        parameters=[
            params_file,
            {'use_sim_time': use_sim_time}
        ]
    )

    # 2. FAST-LIO2 Mapping/Odometry Node (package 'fast_lio' from FAST_LIO_ROS2)
    # Remap /path -> /fastlio2/path to avoid topic name collisions
    fastlio_mapping_node = Node(
        package='fast_lio',
        executable='fastlio_mapping',
        name='laser_mapping',
        output='screen',
        parameters=[
            params_file,
            {'use_sim_time': use_sim_time}
        ],
        remappings=[
            ('/path', '/fastlio2/path')
        ]
    )

    # 3. Optional RViz2 Node
    rviz_node = Node(
        package='rviz2',
        executable='rviz2',
        name='rviz2_fastlio2',
        arguments=['-d', LaunchConfiguration('rviz_config')],
        output='screen',
        parameters=[{'use_sim_time': use_sim_time}],
        condition=IfCondition(LaunchConfiguration('use_rviz'))
    )

    return LaunchDescription([
        params_arg,
        use_sim_time_arg,
        scan_topic_arg,
        imu_topic_arg,
        odom_topic_arg,
        publish_odom_tf_arg,
        use_rviz_arg,
        rviz_config_arg,
        fastlio_bridge_node,
        fastlio_mapping_node,
        rviz_node
    ])
